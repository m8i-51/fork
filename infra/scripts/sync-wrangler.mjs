#!/usr/bin/env node
/**
 * Terraform outputs → wrangler env overlay
 * Usage: node infra/scripts/sync-wrangler.mjs staging
 */
import { execSync, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const env = process.argv[2];
if (!env || !["staging", "production"].includes(env)) {
  console.error("Usage: node infra/scripts/sync-wrangler.mjs <staging|production>");
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const tfDir = join(root, "infra/terraform");
const outDir = join(root, "infra/generated");

const raw = execSync("terraform output -json", { cwd: tfDir, encoding: "utf8" });
const outputs = Object.fromEntries(
  Object.entries(JSON.parse(raw)).map(([k, v]) => [k, v.value]),
);

if (outputs.environment !== env) {
  console.error(`Terraform state environment is '${outputs.environment}', expected '${env}'.`);
  console.error("Run: infra/scripts/apply.sh apply", env);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const overlay = `# Generated by infra/scripts/sync-wrangler.mjs — do not edit by hand
# Reproduce: npm run infra:apply -- ${env}

[env.${env}]
name = "${outputs.worker_name}"
vars = { APP_URL = "${outputs.app_url}" }

[[env.${env}.d1_databases]]
binding = "DB"
database_name = "${outputs.d1_database_name}"
database_id = "${outputs.d1_database_id}"
migrations_dir = "packages/db/migrations"

[[env.${env}.kv_namespaces]]
binding = "KV"
id = "${outputs.kv_namespace_id}"
`;

const outPath = join(outDir, `wrangler.${env}.toml`);
writeFileSync(outPath, overlay, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`  D1: ${outputs.d1_database_id}`);
console.log(`  KV: ${outputs.kv_namespace_id}`);

const merge = spawnSync(process.execPath, ["infra/scripts/merge-wrangler-config.mjs", env], {
  cwd: root,
  stdio: "inherit",
});
if (merge.status !== 0) {
  process.exit(merge.status ?? 1);
}
