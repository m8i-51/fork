#!/usr/bin/env node
/**
 * CI / 手動用: 環境変数から wrangler env overlay を生成
 * Terraform state がなくてもデプロイ可能にする
 *
 * Usage: node infra/scripts/render-wrangler-overlay.mjs <staging|production>
 *
 * Required env:
 *   APP_URL, D1_DATABASE_ID, D1_DATABASE_NAME, KV_NAMESPACE_ID
 * Optional:
 *   WORKER_NAME (default: fork-api-<env>)
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const env = process.argv[2];
if (!env || !["staging", "production"].includes(env)) {
  console.error("Usage: node infra/scripts/render-wrangler-overlay.mjs <staging|production>");
  process.exit(1);
}

const required = ["APP_URL", "D1_DATABASE_ID", "D1_DATABASE_NAME", "KV_NAMESPACE_ID"];
const missing = required.filter((k) => !process.env[k]?.trim());
if (missing.length > 0) {
  console.error(`Missing env: ${missing.join(", ")}`);
  process.exit(1);
}

const workerName = process.env.WORKER_NAME?.trim() || `fork-api-${env}`;
const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const outDir = join(root, "infra/generated");
mkdirSync(outDir, { recursive: true });

const overlay = `# Generated by infra/scripts/render-wrangler-overlay.mjs — do not edit by hand

[env.${env}]
name = "${workerName}"
vars = { APP_URL = "${process.env.APP_URL}" }

[[env.${env}.d1_databases]]
binding = "DB"
database_name = "${process.env.D1_DATABASE_NAME}"
database_id = "${process.env.D1_DATABASE_ID}"
migrations_dir = "packages/db/migrations"

[[env.${env}.kv_namespaces]]
binding = "KV"
id = "${process.env.KV_NAMESPACE_ID}"
`;

const outPath = join(outDir, `wrangler.${env}.toml`);
writeFileSync(outPath, overlay, "utf8");
console.log(`Wrote ${outPath}`);
